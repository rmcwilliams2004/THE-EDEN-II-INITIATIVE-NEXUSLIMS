/**
 * Generates synthetic historical telemetry points for a given node.
 */
export function generateMockTelemetryForNode(nodeId: string, count = 24): TelemetryLog[] {
  const node = MOCK_HARDWARE_NODES.find(n => n.id === nodeId);
  const agronomy = node?.agronomyProfileId ? MOCK_AGRONOMY_PROFILES[node.agronomyProfileId] : undefined;
  
  const basePh = agronomy?.phBaseline ?? (node?.metrics?.ph ?? 6.8);
  const basePressure = node?.metrics?.pressure ?? 600;
  const baseTemp = node?.metrics?.temp ?? 385;
  const baseMoisture = agronomy?.soilMoistureIndex ?? (node?.metrics?.moisturePercent ?? 45);

  const logs: TelemetryLog[] = [];
  const now = Date.now();

  for (let i = count - 1; i >= 0; i--) {
    const timestamp = new Date(now - i * 1000 * 60 * 15).toISOString(); // every 15 mins
    const phNoise = (Math.sin(i * 0.4) * 0.15) + (Math.random() * 0.1 - 0.05);
    const pressNoise = (Math.cos(i * 0.3) * 12) + (Math.random() * 8 - 4);
    const tempNoise = (Math.sin(i * 0.2) * 15) + (Math.random() * 6 - 3);
    const moistureNoise = (Math.cos(i * 0.5) * 4) + (Math.random() * 2 - 1);

    logs.push({
      id: `tel_${nodeId}_${i}`,
      nodeId,
      timestamp,
      phLevel: Number((basePh + phNoise).toFixed(2)),
      pressureBar: Number((basePressure + pressNoise).toFixed(1)),
      temperatureC: Number((baseTemp + tempNoise).toFixed(1)),
      moisturePercent: Number(Math.max(5, Math.min(95, baseMoisture + moistureNoise)).toFixed(1)),
    });
  }

  return logs;
}

/**
 * Returns the complete regional dataset bundle.
 */
export function getRegionalNodeData(nodeId: string): RegionalNodeData | null {
  const node = MOCK_HARDWARE_NODES.find(n => n.id === nodeId);
  if (!node) return null;

  const user = MOCK_GLOBAL_USERS[node.ownerId] || MOCK_GLOBAL_USERS['u_001'];
  const agronomyProfile = (node.agronomyProfileId && MOCK_AGRONOMY_PROFILES[node.agronomyProfileId]) 
    ? MOCK_AGRONOMY_PROFILES[node.agronomyProfileId] 
    : MOCK_AGRONOMY_PROFILES['prof_US_CAL'];
  const recentTelemetry = generateMockTelemetryForNode(nodeId, 24);

  return {
    node,
    user,
    agronomyProfile,
    recentTelemetry,
  };
}

/**
 * Queries nodes by regional cluster.
 */
export function getNodesByRegion(region: string): HardwareNode[] {
  if (region === 'ALL' || !region) return MOCK_HARDWARE_NODES;
  return MOCK_HARDWARE_NODES.filter(n => n.region === region || n.country === region);
}

